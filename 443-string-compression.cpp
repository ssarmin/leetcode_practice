//https://leetcode.com/problems/string-compression/
class Solution {
public:
    int compress(vector<char>& chars) {
        if(chars.size() == 0)
            return 0;
        int count = 1;
        char prev = chars[0];
        int index = 0;
        for(int i=1; i<chars.size(); i++){
            if(prev == chars[i]){
                count++;
            }else{
                if(count > 1){
                    chars[index++] = prev;
                    string str = to_string(count);
                    for(auto s: str){
                        chars[index++] = s;
                    } 
                }else{
                    chars[index++] = prev;
                }
                count = 1;
                prev = chars[i];
            }
        }
        if(count > 1){
            chars[index++] = prev;
            string str = to_string(count);
            for(auto s: str){
                chars[index++] = s;
            } 
        }else{
            chars[index++] = prev;
        }
        return index;
        
    }
};

