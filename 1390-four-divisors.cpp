//https://leetcode.com/problems/four-divisors/
class Solution {
public:
    int sumFourDivisors(vector<int>& nums) {
        unordered_map<int, int> m;
        int res = 0;
        for(auto n: nums){
            if(m.count(n)){
                res += m[n];
                continue;
            }
            int count = 0;
            int sum = 0;
            for(int i=1; i*i<=n; i++){
                if((n%i) == 0){
                    if(i*i == n){
                        count++;
                        sum += i;
                    }else{
                        count += 2;
                        sum += i;
                        sum += n/i;
                    }
                }
                if(count > 4){
                    m[n] = 0;
                    break;
                }
            }
            if(count == 4){
                m[n] = sum;
                res += m[n];
            }
        }
        return res;
    }
};
