//https://leetcode.com/problems/top-k-frequent-words/
class Solution {
public:
    vector<string> topKFrequent(vector<string>& words, int k) {
        unordered_map<string, int> m;
        for(auto str: words){
            m[str]++;
        }

        vector<string> res;
        map<int, vector<string>> m_rev;

        for(auto a: m){
            m_rev[a.second].push_back(a.first);
        }

        for(auto it=m_rev.rbegin(); it!=m_rev.rend() && k; it++){
            vector<string> temp = it->second;
            sort(temp.begin(), temp.end());

            int min_val = min(k, (int)temp.size());
            res.insert(res.end(), temp.begin(), temp.begin()+min_val);
            k -= min_val;
        }

        return res;
    }
};

