//https://leetcode.com/problems/cyclically-rotating-a-grid/
class Solution {
public:
    vector<vector<int>> rotateGrid(vector<vector<int>>& grid, int k) {
        int row = grid.size();
        int col = grid[0].size();

        int iter = min(row, col)/2;
        for(int i=0; i<iter; i++){
            int s_row = i;
            int s_col = i;
            int e_col = col-i;
            int e_row = row-i;

            int rotate = 2*((e_row - s_row - 1) + (e_col - s_col - 1));
            vector<int> temp(rotate, -1);
            rotate = k%rotate;
            int index = 0;
            for(int c=s_col, r = s_row; r >= s_row && r < e_row && c >= s_col && c<e_col; r++){
                temp[index++] = grid[r][c];
            }
            s_col++;
            for(int c=s_col, r = e_row-1; r >= s_row && r < e_row && c >= s_col && c<e_col; c++){
                temp[index++] = grid[r][c];
            }
            e_row--;
            for(int c=e_col-1, r = e_row-1; r >= s_row && r < e_row && c >= s_col && c<e_col; r--){
                temp[index++] = grid[r][c];
            }
            e_col--;
            for(int c=e_col-1, r = s_row; r >= s_row && r < e_row && c >= s_col && c<e_col; c--){
                temp[index++] = grid[r][c];
            }
            s_row++;
            vector<int> v = temp;
            index = 0;
            for(int j=temp.size()-rotate; j<temp.size(); j++){
                v[index++] = temp[j];
            }
            for(int j=0; j<temp.size()-rotate; j++){
                v[index++] = temp[j];
            }

            //put back
            s_row = i;
            s_col = i;
            e_col = col-i;
            e_row = row-i;

            index = 0;
            for(int c=s_col, r = s_row; r >= s_row && r < e_row && c >= s_col && c<e_col; r++){
                grid[r][c] = v[index++];
            }
            s_col++;
            for(int c=s_col, r = e_row-1; r >= s_row && r < e_row && c >= s_col && c<e_col; c++){
                grid[r][c] = v[index++];
            }
            e_row--;
            for(int c=e_col-1, r = e_row-1; r >= s_row && r < e_row && c >= s_col && c<e_col; r--){
                grid[r][c] = v[index++];
            }
            e_col--;
            for(int c=e_col-1, r = s_row; r >= s_row && r < e_row && c >= s_col && c<e_col; c--){
                grid[r][c] = v[index++];
            }
            s_row++;
        }

        return grid;
    }
};

