//https://leetcode.com/problems/magic-squares-in-grid/
class Solution {
public:
    int numMagicSquaresInside(vector<vector<int>>& grid) {
        int row = grid.size();
        int col = grid[0].size();
        int dx[] = {0, 0, 1, -1, -1, 1, 1, -1};
        int dy[] = {1, -1, 0, 0, -1, 1, -1, 1};
        int count = 0;
        for(int r=1; r<row-1; r++){
            for(int c=1; c<col-1; c++){
                vector<bool> v(9, false);
                int t = 0;
                if(grid[r][c] < 10 && grid[r][c] >= 1){
                    v[grid[r][c] - 1] = true;
                    t++;
                }else
                    continue;
                for(int i=0; i<8; i++){
                    int x = dx[i] + r;
                    int y = dy[i] + c;
                    if(grid[x][y] < 10 && grid[x][y] >= 1){
                        if(v[grid[x][y] - 1])
                            break;
                        v[grid[x][y] - 1] = true;
                        t++;
                    }else{
                        break;
                    }
                }
                if(t == 9){
                    int vert1 = grid[r][c-1] + grid[r-1][c-1] + grid[r+1][c-1];
                    int vert2 = grid[r][c] + grid[r-1][c] + grid[r+1][c];
                    int vert3 = grid[r][c+1] + grid[r-1][c+1] + grid[r+1][c+1];

                    int horz1 = grid[r-1][c] + grid[r-1][c-1] + grid[r-1][c+1];
                    int horz2 = grid[r][c] + grid[r][c-1] + grid[r][c+1];
                    int horz3 = grid[r+1][c] + grid[r+1][c-1] + grid[r+1][c+1];
                    
                    int dig1 = grid[r][c] + grid[r+1][c+1] + grid[r-1][c-1];
                    int dig2 = grid[r][c] + grid[r+1][c-1] + grid[r-1][c+1];
                    if(vert1 == horz1 && vert1 == vert2 && vert1 == vert3 && vert1 == horz2 && vert1 == horz3 && vert1 == dig1 && vert1 == dig2){
                        count++;
                    }
                }
            }
        }
        return count;
    }
};

