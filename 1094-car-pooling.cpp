//https://leetcode.com/problems/car-pooling/
class Solution {
public:
    bool carPooling(vector<vector<int>>& trips, int capacity) {
        map<int, int> m;
        for(auto t: trips){
            m[t[1]] += t[0];
            m[t[2]] -= t[0];
            if(m[t[1]] > capacity)
                return false;
        }
        int count = 0;
        for(auto a: m){
            count += a.second;
            if(count > capacity)
                return false;
        }
        return true;
    }
};
